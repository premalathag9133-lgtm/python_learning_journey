''' 
To print backslash: \\
To print single quote: \'
To print double quote: \"
To print new line(break line): \n
To print Tab: \t
To print carriage return: \r
To print backspace: \b
To print vertical Tab: \v
'''

#Example:
a='True\\False'
b='Harry\'s car'
c='Apple is in \"red\" colour.'
d='Good Morning!\nHave a nice Day!'
e='Black\tboard'
f='my name is premalatha, \rI am a BTech student now.'
g='abc\bd'
i='Hello,\vHow are you?'
print(f"{a}\n{b}\n{c}\n{d}\n{e}\n{f}\n{g}\n{i}\n")
